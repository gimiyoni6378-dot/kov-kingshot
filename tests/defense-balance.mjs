import assert from 'node:assert/strict';
import {runBatch} from '../scripts/simulate-defense.mjs';
const suite=runBatch();
assert.equal(suite.cases,108);
assert.deepEqual(suite.startingConditions,{gold:200,units:0});
assert.ok(suite.results.every(run=>run.startingGold===200&&run.startingUnits===0));
assert.ok(suite.cleared10>=3&&suite.cleared10<=6,'Hard balance should retain a few legal winning policies');
assert.ok(suite.reached10<=20,'Fewer sampled policies should reach the final wave');
assert.ok(suite.results.filter(run=>run.reached>=5).length>=65,'The opening must remain playable');
assert.equal(suite.results.filter(run=>run.won&&run.weights.filter(w=>w>0).length===1).length,0,'Single-type recruitment should not dominate this strategy suite');
console.log(`PASS: ${suite.reached10}/108 reach wave 10, ${suite.cleared10}/108 clear; mixed wins exist and sampled single-type policies fail`);
